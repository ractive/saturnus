//! A model's command catalog: the names from the ROM's libraries
//! ([`crate::names`]) with their library and command numbers, as
//! `crates/saturnus-cli/data/commands/<model>.json`, and the ROM's menus that offer each one
//! ([`crate::menus`]).

use std::path::Path;

use anyhow::Result;
use saturnus_core::Model;
use saturnus_kermit::Emulator;
use serde::{Deserialize, Serialize};

use crate::names;

/// One command of the catalog.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Command {
    /// The name as the ROM prints it.
    pub name: String,
    /// Library and command numbers (`XLIB lib n`); some names have two
    /// (the alternate forms of `+`, `∂`, `∫`). None on the 28S.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub xlib: Vec<[u32; 2]>,
    /// The ROM's menus that offer it (`MTH PARTS`; `MENU n` for a menu no
    /// key or submenu label names), from `saturnus-refgen menus`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub menus: Vec<String>,
}

/// A key that opens a root menu.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct MenuKey {
    /// The menu's number (`n MENU`); none on the 28S.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub menu: Option<u32>,
    /// The key's legend (the label on the key or the shifted label above
    /// it), which names the menu.
    pub key: String,
}

/// A model's catalog file.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Catalog {
    /// `48sx`, `48gx`, `49g` or `28s`.
    pub model: String,
    /// How the data was made.
    pub method: String,
    /// Which key opens which root menu, observed on the ROM
    /// (`saturnus-refgen menus`).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub menu_keys: Vec<MenuKey>,
    /// The commands in library and number order.
    pub commands: Vec<Command>,
}

/// What the catalog's `method` says.
pub(crate) const METHOD: &str = "Generated by saturnus-refgen from the ROM on the emulator: the names of \
                      every library's commands, read by decompiling XLIB names (the ROM's own \
                      name tables); the menus that offer each, from the ROM's menu definitions \
                      named by the keys that open them (saturnus-refgen menus).";

/// The model name as the tools take it.
pub fn model_name(model: Model) -> &'static str {
    model.name()
}

/// Boot `model`. Its Kermit link runs on emulated time only, so every run
/// of the generators is the same.
pub fn boot(model: Model, rom: &Path) -> Result<Emulator> {
    Emulator::boot(model, rom, false)
}

/// Build the catalog of `model` from the ROM at `rom`.
pub fn generate(model: Model, rom: &Path) -> Result<Catalog> {
    let mut emu = boot(model, rom)?;
    emu.start_server()?;
    let entries = names::extract(&mut emu)?;
    emu.stop_server()?;
    Ok(assemble(model, &entries))
}

/// What the 28S catalog's `method` says.
pub(crate) const METHOD_28S: &str = "Generated by saturnus-refgen from the ROM on the emulator: the names \
                      as the 28S's CATALOG steps through them, read off the display. The \
                      28S has no serial port and no Kermit server. The menus that offer each \
                      command, and the keys that open them, are from the HP-28S Reference \
                      Manual's dictionary, which lists every menu's rows of labels.";

/// The 28S catalog from the ROM at `rom`: the CATALOG's names in its
/// order, with the menus and menu keys of `old` (the file being
/// replaced) kept by name.
pub fn generate_28s(rom: &Path, old: Option<&Catalog>) -> Result<Catalog> {
    let (mut emu, _, font) = crate::hp28::boot(rom)?;
    let names = crate::hp28::catalog_names(&mut emu, &font)?;
    Ok(assemble_28s(names, old))
}

fn assemble_28s(names: Vec<String>, old: Option<&Catalog>) -> Catalog {
    let menus = |name: &str| {
        old.and_then(|o| o.commands.iter().find(|c| c.name == name))
            .map(|c| c.menus.clone())
            .unwrap_or_default()
    };
    Catalog {
        model: model_name(Model::Hp28s).to_string(),
        method: METHOD_28S.to_string(),
        menu_keys: old.map(|o| o.menu_keys.clone()).unwrap_or_default(),
        commands: names
            .into_iter()
            .map(|name| Command {
                menus: menus(&name),
                name,
                xlib: Vec::new(),
            })
            .collect(),
    }
}

/// One entry per name, with every number it has.
fn assemble(model: Model, entries: &[names::Entry]) -> Catalog {
    let mut commands: Vec<Command> = Vec::new();
    for e in entries {
        match commands.iter_mut().find(|c| c.name == e.name) {
            Some(c) => c.xlib.push([e.lib, e.number]),
            None => commands.push(Command {
                name: e.name.clone(),
                xlib: vec![[e.lib, e.number]],
                menus: Vec::new(),
            }),
        }
    }
    Catalog {
        model: model_name(model).to_string(),
        method: METHOD.to_string(),
        menu_keys: Vec::new(),
        commands,
    }
}

/// The catalog as the file holds it: pretty JSON and a final newline.
pub fn to_file_text(catalog: &Catalog) -> Result<String> {
    Ok(serde_json::to_string_pretty(catalog)? + "\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_with_two_numbers_are_one_entry() {
        let entry = |number, name: &str| names::Entry {
            lib: 2,
            number,
            name: name.into(),
        };
        let cat = assemble(
            Model::Hp48sx,
            &[entry(0, "ABS"), entry(1, "SINH"), entry(2, "ABS")],
        );
        assert_eq!(cat.model, "48sx");
        assert_eq!(cat.commands.len(), 2);
        assert_eq!(cat.commands[0].xlib, [[2, 0], [2, 2]]);
        assert_eq!(cat.commands[1].name, "SINH");
    }

    #[test]
    fn the_28s_catalog_keeps_the_manual_menus_by_name() {
        let old = assemble_28s(vec!["SIN".into(), "GONE".into()], None);
        let mut old = old;
        old.commands[0].menus = vec!["TRIG".into()];
        old.menu_keys = vec![MenuKey {
            menu: None,
            key: "TRIG".into(),
        }];
        let cat = assemble_28s(vec!["ABS".into(), "SIN".into()], Some(&old));
        assert_eq!(cat.commands[1].menus, ["TRIG"]);
        assert!(cat.commands[0].menus.is_empty() && cat.commands[0].xlib.is_empty());
        assert_eq!(cat.menu_keys, old.menu_keys);
        let text = to_file_text(&cat).unwrap();
        assert!(
            !text.contains("xlib") && !text.contains("\"menu\""),
            "{text}"
        );
    }
}
