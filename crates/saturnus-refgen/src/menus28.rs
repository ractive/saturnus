//! The 28S's menus by number, each with its labels in key order
//! (`crates/saturnus-host/src/menulabels/menus-28s.json`), for the menu
//! keys' tooltips: the 28S keeps the number of the menu shown and the
//! first label shown in RAM (#C0151 and #C0153, wiki: hardware/hp28s
//! "Menu in RAM"), but builds the label texts anew at moving places on
//! every redraw, so the labels of each menu come from this table.
//!
//! Generated on the emulator: each key that opens a menu is pressed, the
//! menu's number read from RAM, and its pages shown one after another
//! with NEXT, each label read off the display ([`crate::lcdtext`]'s menu
//! boxes). The label font is learned first, from what the calculator is
//! made to show: variable names in the USER menu (letters and digits), a
//! custom menu of commands whose names hold the other characters
//! (`{ STO+ STO- ... } MENU`), and the mark a mode's label gets when it
//! is on (RAD pressed in the MODE menu). No glyph table is kept. A label
//! that still holds a letter not learned stops the run: nothing is
//! guessed.
//!
//! Each menu is named after the catalog's menu (from the HP-28S
//! Reference Manual) that holds most of its labels, and a label is the
//! command of that name the catalog puts in that menu (or the one whose
//! name it starts, for the labels the box cuts short: `UNTI`). The
//! catalog's commands of a menu that no label shows are reported.

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::{Result, bail};
use saturnus_kermit::Emulator;
use serde::{Deserialize, Serialize};

use crate::catalog::Catalog;
use crate::hp28;
use crate::lcdtext::{self, BOXES, Glyphs, UNKNOWN};

/// Where the 28S keeps the menu's number (two nibbles, low first).
pub const MENU_NUMBER: u32 = 0xC0151;
/// Where it keeps the first label shown, from 0 (two nibbles).
pub const FIRST_LABEL: u32 = 0xC0153;
/// The USER menu: the variables, not a fixed table.
pub const USER: u32 = 23;
/// The mark after a mode's label while the mode is on.
pub const MARK: char = '■';

/// The keys that open a menu, each with the catalog's name for it: the
/// shifted letters A to O, MODE, TRIG, LOGS, SOLV and PLOT.
fn menu_keys(cat: &Catalog) -> Vec<(String, String)> {
    let names: Vec<&str> = cat.menu_keys.iter().map(|k| k.key.as_str()).collect();
    let mut keys: Vec<String> = ('a'..='o').map(|c| format!("shift letter{c}")).collect();
    for k in ["shift cursor", "trig", "shift trig", "solv", "shift solv"] {
        keys.push(k.to_string());
    }
    keys.into_iter()
        .zip(names.iter().map(|s| s.to_string()))
        .collect()
}

/// One menu key: its label and, where the catalog has it in this menu,
/// the command it runs.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Key {
    pub label: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub command: Option<String>,
}

/// One menu: its name in the catalog, what opens it and its keys in
/// order (`None` for a blank key), six to a page.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Menu {
    pub name: String,
    /// The keys that opened it.
    pub keys: String,
    pub labels: Vec<Option<Key>>,
}

/// The table: what it is, and the menus by number.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Table {
    pub method: String,
    pub menus: BTreeMap<u32, Menu>,
}

const METHOD: &str = "Generated by saturnus-refgen (menus28) from the 28S ROM on the emulator: \
    each menu opened by its key, its number read from RAM (#C0151; the first label shown at \
    #C0153), its pages shown with NEXT and the labels read off the display (a mode's mark \
    left out). Each menu is named after the catalog's menu (HP-28S Reference Manual) that \
    holds most of its labels, and a label's command is the catalog's command of that name in \
    that menu. The USER menu (23) shows the variables and is not listed.";

fn peek2(emu: &mut Emulator, at: u32) -> u32 {
    emu.with_machine(|m| u32::from(m.peek(at)) | (u32::from(m.peek(at + 1)) << 4))
}

/// The six boxes' columns now (empty for a blank box).
fn boxes(emu: &mut Emulator) -> Vec<Vec<u8>> {
    let lcd = hp28::lcd(emu);
    (0..BOXES).map(|b| lcdtext::box_columns(&lcd, b)).collect()
}

/// Learn the letters and digits from variable names in the USER menu.
fn learn_letters(emu: &mut Emulator, glyphs: &mut Glyphs) -> Result<()> {
    // Three letters fit any box.
    for name in [
        "ABC", "DEF", "GHI", "JKL", "MNO", "PQR", "STU", "VWX", "YZ0", "A12", "A34", "A56", "A78",
        "A9",
    ] {
        hp28::run_text(emu, &format!("1 '{name}' STO"))?;
        emu.press_keys("user\nwait-idle 5000")?;
        let cols = boxes(emu);
        if let Err(e) = glyphs.check_label(&cols[0], name) {
            bail!(
                "the USER menu does not show {name} in its first box: {}",
                e.shown
            );
        }
        hp28::run_text(emu, &format!("'{name}' PURGE"))?;
    }
    Ok(())
}

/// Command names that hold the characters variable names cannot: shown
/// in a custom menu (`{ ... } MENU`), six at a time, each box checked
/// against the name typed, which teaches its new characters.
const SYMBOLS: [&[&str]; 3] = [
    &["STO+", "STO-", "STO*", "STO/", "Σ+", "Σ-"],
    &["HMS+", "HMS-", "==", "%T", "→LIST", "R→C"],
    &["FS?", "*W", "NΣ", "MAXΣ", "LCD→", "P→R"],
];

fn learn_symbols(emu: &mut Emulator, start: &[u8], glyphs: &mut Glyphs) -> Result<()> {
    for names in SYMBOLS {
        emu.load_state(start)?;
        hp28::run_text(emu, &format!("{{ {} }} MENU", names.join(" ")))?;
        let cols = boxes(emu);
        for (name, c) in names.iter().zip(&cols) {
            if let Err(e) = glyphs.check_label(c, name) {
                bail!("the custom menu does not show {name}: {}", e.shown);
            }
        }
    }
    // The comma: no command has one, so from two strings in a custom
    // menu, "X" and "X,": what the second shows between the first's
    // columns.
    emu.load_state(start)?;
    hp28::run_text(emu, "{ \"X\" \"X,\" } MENU")?;
    let cols = boxes(emu);
    let comma = between(&cols[0], &cols[1]);
    if comma.is_empty() {
        bail!("the custom menu shows \"X\" and \"X,\" alike");
    }
    glyphs.learn_letter(',', &comma);
    if !glyphs.read_box(&cols[1]).contains("X,") {
        bail!("\"X,\" reads {}", glyphs.read_box(&cols[1]));
    }
    Ok(())
}

/// The columns `longer` has between what it shares with `shorter` at
/// its start and at its end.
fn between(shorter: &[u8], longer: &[u8]) -> Vec<u8> {
    let p = shorter
        .iter()
        .zip(longer)
        .take_while(|(a, b)| a == b)
        .count();
    let s = shorter
        .iter()
        .rev()
        .zip(longer.iter().rev())
        .take_while(|(a, b)| a == b)
        .count()
        .min(shorter.len() - p);
    let mid = &longer[p..longer.len().saturating_sub(s).max(p)];
    let start = mid.iter().position(|&c| c != 0).unwrap_or(mid.len());
    let end = mid.iter().rposition(|&c| c != 0).map_or(start, |e| e + 1);
    mid[start..end].to_vec()
}

/// Learn the mode mark: in the MODE menu RAD's box gains a mark when RAD
/// is pressed, and DEG's loses it.
fn learn_mark(emu: &mut Emulator, start: &[u8], glyphs: &mut Glyphs) -> Result<()> {
    emu.load_state(start)?;
    emu.press_keys("shift cursor\nwait-idle 5000")?;
    let before = boxes(emu);
    if glyphs.read_box(&before[5]) != "RAD" {
        bail!(
            "MODE's sixth key does not read RAD: {}",
            glyphs.read_box(&before[5])
        );
    }
    emu.press_keys("f\nwait-idle 5000")?;
    let after = boxes(emu);
    let label = format!("RAD{MARK}");
    if let Err(e) = glyphs.check_label(&after[5], &label) {
        bail!("RAD pressed does not read {label}: {}", e.shown);
    }
    if glyphs.read_box(&after[4]) != "DEG" {
        bail!("DEG keeps a mark after RAD: {}", glyphs.read_box(&after[4]));
    }
    Ok(())
}

/// The command a label in menu `menu` runs: the catalog's command of
/// that name in that menu, or the one there whose name the label starts
/// (a name the box cuts short), if only one.
fn command_of(cat: &Catalog, menu: &str, label: &str) -> Option<String> {
    let here = || {
        cat.commands
            .iter()
            .filter(move |c| c.menus.iter().any(|m| m == menu))
    };
    if let Some(c) = here().find(|c| c.name == label) {
        return Some(c.name.clone());
    }
    let longer: Vec<&str> = here()
        .filter(|c| label.chars().count() >= 4 && c.name.starts_with(label))
        .map(|c| c.name.as_str())
        .collect();
    match longer.as_slice() {
        [one] => Some((*one).to_string()),
        _ => None,
    }
}

/// Build the table on the 28S ROM at `rom`; `cat` is the 28S's catalog
/// (its menus from the Reference Manual).
pub fn generate(rom: &Path, cat: &Catalog) -> Result<Table> {
    let mut emu = hp28::boot(rom)?.0;
    let start = emu.save_state();
    let mut glyphs = Glyphs::default();
    learn_letters(&mut emu, &mut glyphs)?;
    learn_symbols(&mut emu, &start, &mut glyphs)?;
    learn_mark(&mut emu, &start, &mut glyphs)?;
    let mut menus = BTreeMap::new();
    for (keys, expected) in menu_keys(cat) {
        emu.load_state(&start)?;
        emu.press_keys(&format!("{keys}\nwait-idle 5000"))?;
        let n = peek2(&mut emu, MENU_NUMBER);
        if n == 0 || n == USER || menus.contains_key(&n) {
            bail!("{keys}: menu number {n}, not a menu of its own");
        }
        if peek2(&mut emu, FIRST_LABEL) != 0 {
            bail!(
                "{keys}: menu {n} opened on label {}",
                peek2(&mut emu, FIRST_LABEL)
            );
        }
        let mut cols = Vec::new();
        for page in 0..10u32 {
            cols.extend(boxes(&mut emu));
            emu.press_keys("nxt\nwait-idle 5000")?;
            let first = peek2(&mut emu, FIRST_LABEL);
            if first == 0 {
                break;
            }
            if first != 6 * (page + 1) {
                bail!("{keys}: NEXT went to label {first}");
            }
        }
        let mut read: Vec<Option<String>> = cols
            .iter()
            .map(|c| (!c.is_empty()).then(|| glyphs.read_box(c)))
            .collect();
        while read.last().is_some_and(Option::is_none) {
            read.pop();
        }
        for l in read.iter().flatten() {
            if l.contains(UNKNOWN) {
                bail!("{keys}: menu {n} shows {l}, a letter not learned");
            }
        }
        // The catalog's menu holding most of the labels.
        let count = |menu: &str| {
            read.iter()
                .flatten()
                .filter(|l| command_of(cat, menu, l.trim_end_matches(MARK)).is_some())
                .count()
        };
        let best = cat
            .menu_keys
            .iter()
            .map(|k| k.key.as_str())
            .max_by_key(|m| count(m))
            .unwrap_or_default();
        if best != expected {
            bail!("{keys}: menu {n} holds most of {best}'s commands, not {expected}'s");
        }
        let labels: Vec<Option<Key>> = read
            .into_iter()
            .map(|l| {
                l.map(|l| {
                    let label = l.trim_end_matches(MARK).to_string();
                    let command = command_of(cat, &expected, &label);
                    Key { label, command }
                })
            })
            .collect();
        let missing: Vec<&str> = cat
            .commands
            .iter()
            .filter(|c| c.menus.contains(&expected))
            .filter(|c| {
                !labels
                    .iter()
                    .flatten()
                    .any(|k| k.command.as_deref() == Some(&c.name))
            })
            .map(|c| c.name.as_str())
            .collect();
        if !missing.is_empty() {
            eprintln!("{expected} (menu {n}): no label for {}", missing.join(" "));
        }
        menus.insert(
            n,
            Menu {
                name: expected,
                keys,
                labels,
            },
        );
    }
    Ok(Table {
        method: METHOD.to_string(),
        menus,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::Command;

    fn cmd(name: &str, menu: &str) -> Command {
        Command {
            name: name.into(),
            xlib: vec![],
            menus: vec![menu.into()],
        }
    }

    #[test]
    fn labels_name_the_commands_of_their_menu() {
        let cat = Catalog {
            model: "28s".into(),
            method: String::new(),
            menu_keys: vec![],
            commands: vec![
                cmd("UNTIL", "BRANCH"),
                cmd("END", "BRANCH"),
                cmd("LAST", "STACK"),
                cmd("DEC", "BINARY"),
            ],
        };
        assert_eq!(command_of(&cat, "BRANCH", "END").as_deref(), Some("END"));
        assert_eq!(
            command_of(&cat, "BRANCH", "UNTI").as_deref(),
            Some("UNTIL"),
            "cut short"
        );
        assert_eq!(command_of(&cat, "MODE", "LAST"), None, "not in that menu");
        assert_eq!(command_of(&cat, "BRANCH", "EN"), None, "too short to say");
        assert_eq!(command_of(&cat, "BINARY", "DEC").as_deref(), Some("DEC"));
    }

    #[test]
    fn a_character_between_two_boxes() {
        let q = [3, 0, 3];
        let x = [27, 4, 27];
        let b0: Vec<u8> = [&q[..], &[0], &x, &[0], &q].concat();
        let b1: Vec<u8> = [&q[..], &[0], &x, &[0], &[16, 8], &[0], &q].concat();
        assert_eq!(between(&b0, &b1), vec![16, 8]);
        assert!(between(&b0, &b0).is_empty());
    }
}
